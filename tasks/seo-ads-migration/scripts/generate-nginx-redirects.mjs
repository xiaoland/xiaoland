import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const repoRoot = process.cwd();
const taskDir = path.join(repoRoot, "tasks/seo-ads-migration");
const csvPath = path.join(taskDir, "old-url-map.csv");
const csv = await readFile(csvPath, "utf8");
const rows = parseCsv(csv).slice(1);

const blocks = [];
for (const row of rows) {
  const [, oldUrl, newUrl] = row;
  const oldPath = new URL(oldUrl).pathname;
  const slashlessOldPath = oldPath.endsWith("/") ? oldPath.slice(0, -1) : "";

  blocks.push(`location = ${oldPath} {
    return 301 ${newUrl};
}`);

  if (slashlessOldPath) {
    blocks.push(`location = ${slashlessOldPath} {
    return 301 ${newUrl};
}`);
  }
}

blocks.push(`location = /index.php/about-page.html {
    return 301 https://lanzhijiang.dev/about;
}`);

blocks.push(`location = /index.php/feed/ {
    return 301 https://lanzhijiang.dev/rss.xml;
}`);

const output = `# Generated by tasks/seo-ads-migration/scripts/generate-nginx-redirects.mjs
# Place before the Typecho fallback rewrite in the old blog vhost.

${blocks.join("\n\n")}
`;

await writeFile(path.join(taskDir, "nginx-article-redirects.conf"), output);

console.log(`Wrote ${blocks.length} redirect blocks to tasks/seo-ads-migration/nginx-article-redirects.conf`);

function parseCsv(input) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;

  for (let index = 0; index < input.length; index++) {
    const char = input[index];
    const next = input[index + 1];

    if (quoted && char === '"' && next === '"') {
      cell += '"';
      index++;
      continue;
    }

    if (char === '"') {
      quoted = !quoted;
      continue;
    }

    if (!quoted && char === ",") {
      row.push(cell);
      cell = "";
      continue;
    }

    if (!quoted && char === "\n") {
      row.push(cell);
      if (row.some((value) => value.length > 0)) {
        rows.push(row);
      }
      row = [];
      cell = "";
      continue;
    }

    cell += char;
  }

  if (cell || row.length) {
    row.push(cell);
    rows.push(row);
  }

  return rows;
}
