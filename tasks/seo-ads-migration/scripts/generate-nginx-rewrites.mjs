import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const repoRoot = process.cwd();
const taskDir = path.join(repoRoot, "tasks/seo-ads-migration");
const csvPath = path.join(taskDir, "old-url-map.csv");
const rows = parseCsv(await readFile(csvPath, "utf8")).slice(1);

const rewrites = [
  "rewrite ^/$ https://lanzhijiang.dev/? permanent;",
  "rewrite ^/index\\.php/?$ https://lanzhijiang.dev/? permanent;",
];

for (const row of rows) {
  const [archiveId, , newUrl] = row;
  rewrites.push(`rewrite ^/index\\.php/archives/${archiveId}/?$ ${newUrl}? permanent;`);
  rewrites.push(`rewrite ^/archives/${archiveId}/?$ ${newUrl}? permanent;`);
}

rewrites.push("rewrite ^/index\\.php/about-page\\.html$ https://lanzhijiang.dev/about? permanent;");
rewrites.push("rewrite ^/about-page\\.html$ https://lanzhijiang.dev/about? permanent;");
rewrites.push("rewrite ^/index\\.php/feed/?$ https://lanzhijiang.dev/rss.xml? permanent;");
rewrites.push("rewrite ^/feed/?$ https://lanzhijiang.dev/rss.xml? permanent;");

const output = `# BEGIN xiaoland seo migration redirects
# Generated by tasks/seo-ads-migration/scripts/generate-nginx-rewrites.mjs
# Keep this block before the Typecho fallback rewrites.
${rewrites.join("\n")}
# END xiaoland seo migration redirects
`;

await writeFile(path.join(taskDir, "nginx-rewrite-redirects.conf"), output);

console.log(`Wrote ${rewrites.length} rewrite rules to tasks/seo-ads-migration/nginx-rewrite-redirects.conf`);

function parseCsv(input) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;

  for (let index = 0; index < input.length; index++) {
    const char = input[index];
    const next = input[index + 1];

    if (quoted && char === '"' && next === '"') {
      cell += '"';
      index++;
      continue;
    }

    if (char === '"') {
      quoted = !quoted;
      continue;
    }

    if (!quoted && char === ",") {
      row.push(cell);
      cell = "";
      continue;
    }

    if (!quoted && char === "\n") {
      row.push(cell);
      if (row.some((value) => value.length > 0)) {
        rows.push(row);
      }
      row = [];
      cell = "";
      continue;
    }

    cell += char;
  }

  if (cell || row.length) {
    row.push(cell);
    rows.push(row);
  }

  return rows;
}
